"""Generate and verify the Phosphor icon name table.

The two bundled TTFs in third_party/phosphor contain every icon, but their
post tables are version 3.0 (no glyph names). The official web package's
regular/style.css is the only source of icon names and code points, so a copy
of it is vendored in third_party/phosphor/metadata.

Usage:
    python tools/gen_phosphor_icons.py          # rewrite PhosphorIcons.generated.h
    python tools/gen_phosphor_icons.py --check # verify header, aliases and fonts

Only the Python standard library is used. The fonts are parsed read-only, so a
name can never point at a code point the bundled fonts cannot draw.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CSS = ROOT / "third_party/phosphor/metadata/regular.css"
HEADER = ROOT / "src/app/PhosphorIcons.generated.h"
ALIASES = ROOT / "src/app/PhosphorAliases.h"
FONTS = (ROOT / "third_party/phosphor/Phosphor.ttf",
         ROOT / "third_party/phosphor/Phosphor-Fill.ttf")
PUA = range(0xE000, 0xF8FF + 1)


def parse_css(path: pathlib.Path) -> list[tuple[str, int]]:
    """Read `.ph.ph-<name>:before { content: "\\e123"; }` rules."""
    pairs: list[tuple[str, int]] = []
    pending: str | None = None
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.search(r"ph-([a-z0-9-]+):before", line)
        if match:
            pending = match.group(1)
            continue
        if pending and "content:" in line:
            value = re.search(r"([0-9a-fA-F]{4,6})", line.split("content:")[1])
            if value:
                pairs.append((pending, int(value.group(1), 16)))
            pending = None
    if not pairs:
        raise ValueError(f"no icon rules found in {path}")
    return sorted(pairs)


def font_cmap(path: pathlib.Path) -> set[int]:
    """All code points mapped by the font's Windows BMP cmap (format 4)."""
    data = path.read_bytes()
    count = struct.unpack_from(">H", data, 4)[0]
    tables = {}
    for i in range(count):
        record = 12 + 16 * i
        tag = data[record:record + 4].decode("latin-1")
        offset, length = struct.unpack_from(">II", data, record + 8)
        tables[tag] = (offset, length)
    base = tables["cmap"][0]
    subtables = [struct.unpack_from(">HHI", data, base + 4 + 8 * i)
                 for i in range(struct.unpack_from(">H", data, base + 2)[0])]
    record = next((r for r in subtables if (r[0], r[1]) == (3, 1)), None)
    if record is None:
        raise ValueError(f"{path.name}: no (3, 1) cmap subtable")
    start = base + record[2]
    if struct.unpack_from(">H", data, start)[0] != 4:
        raise ValueError(f"{path.name}: expected cmap format 4")
    seg_x2 = struct.unpack_from(">H", data, start + 6)[0]
    segments = seg_x2 // 2
    end, begin = start + 14, start + 14 + seg_x2 + 2
    delta, range_offset = begin + seg_x2, begin + 2 * seg_x2
    codes: set[int] = set()
    for i in range(segments):
        last = struct.unpack_from(">H", data, end + 2 * i)[0]
        first = struct.unpack_from(">H", data, begin + 2 * i)[0]
        difference = struct.unpack_from(">h", data, delta + 2 * i)[0]
        offset = struct.unpack_from(">H", data, range_offset + 2 * i)[0]
        if first == 0xFFFF:
            continue
        for code in range(first, last + 1):
            if offset:
                glyph = struct.unpack_from(">H", data,
                                           range_offset + 2 * i + offset + 2 * (code - first))[0]
                glyph = (glyph + difference) & 0xFFFF if glyph else 0
            else:
                glyph = (code + difference) & 0xFFFF
            if glyph:
                codes.add(code)
    return codes


def header_text(pairs: list[tuple[str, int]]) -> str:
    unique = {code for _, code in pairs}
    lines = [
        "// Generated by tools/gen_phosphor_icons.py from",
        "// third_party/phosphor/metadata/regular.css (Phosphor Icons 2.1.2, MIT).",
        "// Do not edit: rerun the generator after changing the vendored CSS.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace ws::phosphor::generated {",
        "",
        "struct Entry {",
        "    std::string_view name;",
        "    char16_t code; // in the same private use area as Segoe's; never used as a Segoe code",
        "};",
        "",
        f"// Sorted by name. {len(pairs)} names, {len(unique)} distinct icon code points.",
        f"inline constexpr std::array<Entry, {len(pairs)}> kNames = {{",
    ]
    for name, code in pairs:
        lines.append(f'    {{"{name}", char16_t(0x{code:04X})}},')
    lines += [
        "};",
        "",
        f"inline constexpr std::size_t kIconCount = {len(unique)};",
        "",
        "} // namespace ws::phosphor::generated",
        "",
    ]
    return "\n".join(lines)


def parse_aliases() -> list[tuple[int, str, bool]]:
    rows: list[tuple[int, str, bool]] = []
    for line in ALIASES.read_text(encoding="utf-8").splitlines():
        match = re.search(r"\{0x([0-9A-Fa-f]{4}),\s*\"([a-z0-9-]+)\",\s*(true|false)\}", line)
        if match:
            rows.append((int(match.group(1), 16), match.group(2), match.group(3) == "true"))
    return rows


def check(pairs: list[tuple[str, int]], regenerate: bool) -> int:
    by_name = dict(pairs)
    expected = header_text(pairs)
    if regenerate:
        HEADER.write_text(expected, encoding="utf-8", newline="\n")
        print(f"wrote {HEADER.relative_to(ROOT)}: {len(pairs)} names")
    elif not HEADER.exists() or HEADER.read_text(encoding="utf-8") != expected:
        print(f"error: {HEADER.relative_to(ROOT)} is out of date; run the generator",
              file=sys.stderr)
        return 1

    cmaps = [font_cmap(path) for path in FONTS]
    if cmaps[0] != cmaps[1]:
        print("error: Regular and Fill fonts have different cmap coverage", file=sys.stderr)
        return 1
    missing = sorted({code for _, code in pairs if code not in cmaps[0]})
    if missing:
        print(f"error: {len(missing)} CSS code points are absent from the fonts, "
              f"first: U+{missing[0]:04X}", file=sys.stderr)
        return 1
    pua = {c for c in cmaps[0] if c in PUA}
    unnamed = len(pua) - len({code for _, code in pairs})
    if unnamed < 0 or unnamed > 1:
        print(f"error: unexpected gap between font PUA glyphs ({len(pua)}) and "
              f"named icons ({len(set(code for _, code in pairs))})", file=sys.stderr)
        return 1

    aliases = parse_aliases()
    if not aliases:
        print(f"error: no aliases found in {ALIASES.relative_to(ROOT)}", file=sys.stderr)
        return 1
    segoe = [row[0] for row in aliases]
    if segoe != sorted(segoe) or len(set(segoe)) != len(segoe):
        print("error: aliases must be sorted by Segoe code point and unique", file=sys.stderr)
        return 1
    for code, name, _ in aliases:
        if by_name.get(name) is None:
            print(f"error: U+{code:04X} names unknown icon {name!r}", file=sys.stderr)
            return 1
        if by_name[name] not in cmaps[0]:
            print(f"error: U+{code:04X} -> {name} is not in the fonts", file=sys.stderr)
            return 1

    print(f"ok: {len(pairs)} names / {len(set(c for _, c in pairs))} icons, "
          f"{len(pua)} PUA glyphs in both fonts, {len(aliases)} Segoe aliases")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify instead of rewriting the generated header")
    args = parser.parse_args()
    return check(parse_css(CSS), regenerate=not args.check)


if __name__ == "__main__":
    raise SystemExit(main())
