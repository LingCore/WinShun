class BITMAPINFOHEADER(ctypes.Structure):
    _fields_ = [("biSize", wt.DWORD), ("biWidth", wt.LONG), ("biHeight", wt.LONG), ("biPlanes", wt.WORD),
                ("biBitCount", wt.WORD), ("biCompression", wt.DWORD), ("biSizeImage", wt.DWORD),
                ("biXPelsPerMeter", wt.LONG), ("biYPelsPerMeter", wt.LONG), ("biClrUsed", wt.DWORD),
                ("biClrImportant", wt.DWORD)]


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def rect_of(hwnd):
    rect = wt.RECT()
    user32.GetWindowRect(wt.HWND(hwnd), ctypes.byref(rect))
    return rect.left, rect.top, rect.right, rect.bottom


def print_window(hwnd):
    """The window's own pixels as DWM composes them (PW_RENDERFULLCONTENT),
    cropped to its visible frame: nothing of what lies behind or beside it."""
    left, top, right, bottom = rect_of(hwnd)
    hwnd = wt.HWND(hwnd)
    visible = wt.RECT()
    dwmapi.DwmGetWindowAttribute(hwnd, 9, ctypes.byref(visible), ctypes.sizeof(visible))  # extended frame bounds
    w, h = right - left, bottom - top
    screen = user32.GetDC(None)
    dc = gdi32.CreateCompatibleDC(screen)
    bitmap = gdi32.CreateCompatibleBitmap(screen, w, h)
    old = gdi32.SelectObject(dc, bitmap)
    try:
        if not user32.PrintWindow(hwnd, dc, 2):
            raise RuntimeError("PrintWindow failed")
        header = BITMAPINFOHEADER(ctypes.sizeof(BITMAPINFOHEADER), w, -h, 1, 32, 0)
        buffer = ctypes.create_string_buffer(w * h * 4)
        gdi32.GetDIBits(dc, bitmap, 0, h, buffer, ctypes.byref(header), 0)
    finally:
        gdi32.SelectObject(dc, old)
        gdi32.DeleteObject(bitmap)
        gdi32.DeleteDC(dc)
        user32.ReleaseDC(None, screen)
    pixels = np.frombuffer(buffer, np.uint8).reshape(h, w, 4)[..., [2, 1, 0]].copy()
    image = Image.fromarray(pixels, "RGB")
    return image.crop((visible.left - left, visible.top - top, visible.right - left, visible.bottom - top))


def foreground_pid():
    pid = wt.DWORD()
    user32.GetWindowThreadProcessId(user32.GetForegroundWindow(), ctypes.byref(pid))
    return pid.value


def press(*chord):
    """The keys of a chord down in order, up in reverse (real input: guarded by the caller)."""
    for vk in chord:
        user32.keybd_event(vk, 0, 0, 0)
        time.sleep(0.05)
    for vk in reversed(chord):
        user32.keybd_event(vk, 0, 2, 0)
        time.sleep(0.05)


def pointer_away(hwnds):
    """The pointer out of the way of the windows shot (hover effects), only if it is over one."""
    point = wt.POINT()
    user32.GetCursorPos(ctypes.byref(point))
    for hwnd in hwnds:
        left, top, right, bottom = rect_of(hwnd)
        if left <= point.x < right and top <= point.y < bottom:
            user32.SetCursorPos(2, 2)
            time.sleep(0.4)
            return True
    return False


def runtime_keys():
    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Software\WinShun\RuntimeTests") as key:
        return winreg.QueryInfoKey(key)[0]


