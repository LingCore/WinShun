"""Make the posters 0.35.0 adds, from the release build's real program.

Two features have no preview fixture of their own (Preview.cpp draws neither
the favorites as tiles nor the video player), so their pictures come from the
production App itself: the release build's WinShun.exe run as

  WinShun.exe --probe-runtime <work>/<run>/live --live --scale <s> --renderer d3d11
              --idle-open-index F:\\Win顺演示

an isolated runtime probe (a private profile in the run's own TEMP, the HKCU
of a private registry key, no hotkeys, no instance mutex: the user's own
Win顺 is not touched). Its windows open on the real desktop and are driven
by lines written to <run>/live/cmd.txt (`show`, `windows`, `press`), the
probe ends when <run>/live/stop appears. The profile is seeded while the
probe is held still (NtSuspendProcess, a few milliseconds, right after its
first save of WinShun.ini): the settings below, favorites.json and
history.txt; nothing of the user's is read. Each window is then taken by
PrintWindow (its own pixels, nothing behind it), so there is no backdrop,
no pointer and nothing of the desktop in it. The windows are opaque
(设置 Transparency off: plain colours, as the offscreen previews draw them) and
get the rounded corners of Windows 11 from art.screen_piece.

  favorites   --scale 2    设置 › 结果列表 › 收藏的样式 = 图标 (Results/FavoriteTiles),
                           nothing typed in 全部: the demo favorites as a grid of tiles
  video       --scale 2    `show 演示视频`, Alt+P (real keys, sent only while the probe's
                           own launcher is the foreground window), the preview opens and
                           plays the demo video; set to 720 logical px wide (the screen
                           is only 1280 x 800 at this scale, the launcher in its middle:
                           beside it the preview would be 458 wide), and taken after a few
                           seconds, playing: the burned-in clock in the picture and the
                           bar's are to agree (looked at in live-shots/video-preview.png;
                           run again if they do not)

The demo video (tools/screenshots/demo/演示视频.mov, also in F:\\Win顺演示) is
made here when missing: 1920x1080 H.264, 15 s, no sound, generated by
Pillow and ffmpeg (the burned-in clock tells which second a shot shows). It
is a MOV because this PC has no friendly name for .mp4 (the preview's header
would say "mp4_auto_file"); the preview plays MP4, MOV, MKV, AVI, WMV alike.

  python tools/screenshots/release035.py --exe <dir>/WinShun.exe --work <fresh dir> --capture-only
  python tools/screenshots/release035.py --exe <dir>/WinShun.exe --work <dir> --export-only

--work must be fresh when capturing; the probe's temporary profiles, logs and
the raw PNGs stay there (build/, not committed). --only favorites|video
captures one of the two (into a fresh --work of its own, to try it).

The launcher goes when something else takes the foreground (an Explorer
window another program opens, say): the shots ask for it again and try
again, and no key is sent unless the probe's own launcher is in front.

Not done here: the sideways long screenshot. The capture plugin's
--preview-long-capture fixture runs a real selection overlay over the whole
desktop and moves the pointer and clicks with SendInput; it is not for a PC
somebody is using.
"""
