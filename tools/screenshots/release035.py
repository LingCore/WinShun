# --- the runtime probe -----------------------------------------------------

class SeedLost(Exception):
    """The probe read its WinShun.ini before the seeding changed it: nothing to retry, run again."""


def require_seeded(info):
    """The seeding is a race (see Live._seed) that fails silently: the poster would show the
    default list and a Mica window. Transparency=off, written in the same go as FavoriteTiles
    and PreviewWith, makes the window's colour opaque (#AARRGGBB, ff); the probe's own default
    is see-through (#00000000)."""
    if not str(info.get("color", "")).lower().startswith("#ff"):
        raise SeedLost(f"the probe did not take the seeded settings (window colour {info.get('color')}): "
                       "it read WinShun.ini first; run again")


class Live:
    """The release build's WinShun.exe as an isolated runtime probe on the real
    desktop (see the module's docstring), seeded with the demo profile."""

    def __init__(self, exe, work, name, scale, favorites, recent):
        self.exe, self.scale = Path(exe), scale
        self.dir = Path(work) / name
        self.temp, self.live = self.dir / "temp", self.dir / "live"
        self.temp.mkdir(parents=True)
        self.live.mkdir()
        self.favorites, self.recent = favorites, recent
        self.batches = 0
        self.seeded = {}
        self.proc = None
        self.keys_before = runtime_keys()

    def __enter__(self):
        env = {**os.environ, "TEMP": str(self.temp), "TMP": str(self.temp), "QT_FONT_DPI": "96", "WINSHUN_RECENT": "own"}
        log = (self.dir / "process.log").open("w", encoding="utf-8")
        self.proc = subprocess.Popen(
            [str(self.exe), "--probe-runtime", str(self.live), "--live", "--scale", str(self.scale), "--renderer", "d3d11",
             "--idle-open-index", str(DEMO)], env=env, stdout=log, stderr=subprocess.STDOUT)
        thread = threading.Thread(target=self._seed, daemon=True)
        thread.start()
        thread.join(90)
        if "profile" not in self.seeded:
            self.stop()
            raise RuntimeError(f"the probe's profile was not seeded: {self.seeded}")
        time.sleep(5)  # the index of the demo folder
        return self

    def __exit__(self, *_):
        self.stop()

    def _seed(self):
        """Hold the probe still right after it saved its WinShun.ini (it reads it
        again a moment later, in App::start), change what the poster needs, put the
        favorites and the history where App::startRuntime reads them, let it go."""
        deadline = time.time() + 60
        profile = None
        while profile is None and time.time() < deadline and self.proc.poll() is None:
            with os.scandir(self.temp) as entries:
                profile = next((Path(e.path) for e in entries if e.name.startswith("WinShun-preview-") and e.is_dir()), None)
            if profile is None:
                time.sleep(0.0005)
        if profile is None:
            return
        ini = profile / "WinShun" / "WinShun.ini"
        while time.time() < deadline and not (ini.exists() and ini.stat().st_size > 0):
            time.sleep(0.0005)
        handle = kernel32.OpenProcess(0x0800, False, self.proc.pid)  # PROCESS_SUSPEND_RESUME
        ntdll.NtSuspendProcess(handle)
        try:
            text = ini.read_text(encoding="utf-8")
            text = stage.ini_set(text, "Results", {"FavoriteTiles": "true", "PreviewWith": "builtin"})
            text = stage.ini_set(text, "Appearance", {"Theme": "light", "Transparency": "off", "UiSize": "standard",
                                                      "Corners": "round"})
            ini.write_text(text, encoding="utf-8")
            entries = [{"kind": kind, "path": str(DEMO / path), "name": name, **({"keyword": key} if key else {})}
                       for kind, path, name, key in self.favorites]
            (profile / "favorites.json").write_text(json.dumps(
                {"format": "winshun-favorites", "version": 1, "favorites": entries}, ensure_ascii=False, indent=2),
                encoding="utf-8")
            now = int(time.time() * 1000)
            lines = [f"{DEMO / path}\t1\t{now - i * 7 * 60_000}" for i, path in enumerate(self.recent)]
            (profile / "history.txt").write_text("\r\n".join(lines) + "\r\n", encoding="utf-8")
        finally:
            ntdll.NtResumeProcess(handle)
            kernel32.CloseHandle(handle)
        self.seeded["profile"] = str(profile)

    def send(self, *lines, wait=20):
        """One batch for the probe's cmd.txt, and until it has been done (ack.txt)."""
        if self.proc.poll() is not None:
            raise RuntimeError("the probe has ended")
        tmp = self.live / "cmd.tmp"
        tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
        os.replace(tmp, self.live / "cmd.txt")
        self.batches += 1
        end = time.time() + wait
        while time.time() < end:
            try:
                if int((self.live / "ack.txt").read_text() or 0) >= self.batches:
                    return
            except (OSError, ValueError):
                pass
            time.sleep(0.05)
        raise RuntimeError(f"the probe did not answer {lines}")

    def windows(self):
        self.send("windows")
        return json.loads((self.live / "windows.json").read_text(encoding="utf-8"))

    def window(self, kind, wait=10):
        """The probe's window of this QML type (Main: the launcher; PreviewWindow)."""
        end = time.time() + wait
        while time.time() < end:
            found = [w for w in self.windows() if w["class"].startswith(kind)]
            if found:
                return int(found[0]["hwnd"]), found[0]
            time.sleep(0.3)
        raise RuntimeError(f"no {kind} window")

    def raise_launcher(self, query="", attempts=8):
        """The launcher up and in front (it goes when something else takes the
        foreground, as an Explorer window another program opens does): asked for
        again until it is."""
        for _ in range(attempts):
            self.send(f"show {query}".strip())
            time.sleep(1.2)
            found = [w for w in self.windows() if w["class"].startswith("Main")]
            if found and foreground_pid() == self.proc.pid:
                return int(found[0]["hwnd"]), found[0]
        raise RuntimeError("the launcher could not be kept in front: something else keeps taking the foreground")

    def wait_rows(self, minimum=200, wait=20):
        """Until the launcher is tall enough to have its rows (the index of the demo folder is up)."""
        end = time.time() + wait
        while time.time() < end:
            found = [w for w in self.windows() if w["class"].startswith("Main")]
            if found and found[0]["h"] >= minimum:
                return
            time.sleep(0.4)
        raise RuntimeError("the launcher shows no rows")

    def require_foreground(self, wait=5):
        end = time.time() + wait
        while time.time() < end:
            if foreground_pid() == self.proc.pid:
                return
            time.sleep(0.1)
        raise RuntimeError("the probe's launcher is not the foreground window (somebody is using the PC): no keys sent")

    def stop(self):
        """Through the stop file only: killing it would leave its registry key and profile."""
        (self.live / "stop").write_text("")
        try:
            self.proc.wait(30)
        except subprocess.TimeoutExpired:
            print("the probe did not end; it is stopped the hard way, its registry key may stay", flush=True)
            self.proc.kill()
            self.proc.wait()
        # 0: its key is gone (another program's probe ending or starting meanwhile shows as -1 or +1)
        self.seeded["registry_keys_net_change"] = runtime_keys() - self.keys_before
        shutil.rmtree(self.temp, ignore_errors=True)  # what the probe left (the clipboard folder it saves on the way out)


def favorites_shot(exe, work, out):
    with Live(exe, work, "favorites", 2, FAVORITES, RECENT) as probe:
        for attempt in range(3):
            hwnd, info = probe.raise_launcher()
            require_seeded(info)
            time.sleep(1.0)
            pointer_away([hwnd])
            time.sleep(0.5)
            if foreground_pid() == probe.proc.pid and any(w["class"].startswith("Main") for w in probe.windows()):
                break  # still up after the pointer moved and the frame settled
        else:
            raise RuntimeError("the launcher did not stay in front")
        image = print_window(hwnd)
        image.save(out / "favorite-tiles.png")
        report = {"window": info, "size": image.size, "seeded": probe.seeded}
    report["registry_keys_net_change"] = probe.seeded["registry_keys_net_change"]
    return report


def video_shot(exe, work, out, seconds=7.6, scale=2, window=720):
    query = Path(VIDEO).stem
    with Live(exe, work, "video", scale, (), ()) as probe:
        for attempt in range(1, 5):
            try:
                launcher, launcher_info = probe.raise_launcher(query)
                require_seeded(launcher_info)
                probe.wait_rows()
                time.sleep(0.5)
                pointer_away([launcher])
                probe.require_foreground()
                press(0x12, 0x50)  # Alt+P, for the first (and only) row: the video
                preview, info = probe.window("PreviewWindow", wait=6)
                require_seeded(info)  # PreviewWith=builtin: Win顺's own preview, not another program's
                opened = time.time()
                # The preview at a width of its own choosing (FilePreview::placeBeside:
                # the picture 16:9 within the width less 32, plus 32 and the 64 of the
                # header): the launcher takes the middle of a screen that is only
                # 1280 x 800 at this scale, so it would be as narrow as 458 logical
                # px beside it, and as wide as 992 where there is room. 720 puts the
                # header and the bar at a size the poster can show.
                picture = round((window - 32) * 9 / 16)
                wide, high = window * scale, (picture + 32 + 64) * scale
                screen = user32.GetSystemMetrics(0), user32.GetSystemMetrics(1)
                user32.SetWindowPos(wt.HWND(preview), None, (screen[0] - wide) // 2, 40, wide, high, 0x0004 | 0x0010)
                time.sleep(max(0.0, seconds - (time.time() - opened)))
                pointer_away([launcher, preview])
                probe.window("PreviewWindow", wait=1)  # still there: the launcher still has the front
                image = print_window(preview)
                break
            except RuntimeError as error:
                print(f"attempt {attempt}: {error}", flush=True)
                probe.send("hide")
                time.sleep(1.5)
        else:
            raise RuntimeError("the video preview was not shot")
        image.save(out / "video-preview.png")
        now = {w["class"].split("_")[0]: w for w in probe.windows()}
        report = {"preview": now["PreviewWindow"], "launcher": now["Main"], "size": image.size, "attempts": attempt,
                  "seeded": probe.seeded}
    report["registry_keys_net_change"] = probe.seeded["registry_keys_net_change"]
    return report


def capture(exe, work, only=()):
    if work.exists():
        sys.exit(f"{work} exists: --work must be a fresh directory when capturing")
    work.mkdir(parents=True)
    video = ensure_demo()
    out = work / "live-shots"
    out.mkdir()
    shooters = {"favorites": favorites_shot, "video": video_shot}
    reports = {name: shooter(exe, work, out) for name, shooter in shooters.items() if not only or name in only}
    (work / "capture.json").write_text(json.dumps({
        "exe": str(exe), "sha256": sha256(exe), "video": str(video), "video_sha256": sha256(video),
        "favorites": [list(f) for f in FAVORITES], "runs": reports,
        "scale": {"favorites": 2, "video": 2}, "renderer": "d3d11",
        "profiles": "isolated runtime probe (--probe-runtime --live); production UI and controllers",
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(reports, ensure_ascii=False, indent=2))


