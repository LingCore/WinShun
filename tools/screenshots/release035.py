def make_demo_video(path, width=1920, height=1080, fps=24, seconds=15):
    """A neutral demo video: bars growing, a dot going round, a clock of whole seconds."""
    def lerp(a, b, t):
        return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))

    base = Image.new("RGB", (width, height))
    paint = ImageDraw.Draw(base)
    for y in range(height):
        paint.line([(0, y), (width, y)], fill=lerp((22, 46, 92), (22, 128, 142), y / (height - 1)))
    glow = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    ImageDraw.Draw(glow).ellipse((1180, -380, 2300, 740), fill=(255, 255, 255, 26))
    base.paste(glow, (0, 0), glow)
    big, medium, small, clock = (ImageFont.truetype(str(art.BOLD), 200), ImageFont.truetype(str(art.BOLD), 96),
                                 ImageFont.truetype(str(art.REGULAR), 44), ImageFont.truetype(str(art.BOLD), 130))

    def frame(t):
        image = base.copy()
        draw = ImageDraw.Draw(image)
        draw.rectangle((140, 170, 212, 180), fill=(255, 187, 51))
        draw.text((140, 190), "Win顺", font=big, fill=(255, 255, 255))
        draw.text((144, 470), "演示视频", font=medium, fill=(255, 255, 255))
        draw.text((144, 610), "2026 年度报告 · 经营回顾与展望", font=small, fill=(196, 218, 232))
        floor, bar, gap, left = 880, 118, 52, 1010
        for i, (label, full) in enumerate(zip(("上年", "Q1", "Q2", "Q3", "Q4"), (250, 350, 430, 560, 690))):
            grow = min(1.0, max(0.0, (t - 0.6 - i * 0.55) / 1.6))
            grow = 1 - (1 - grow) ** 3
            x = left + i * (bar + gap)
            draw.rounded_rectangle((x, floor - full * grow, x + bar, floor), radius=8,
                                   fill=(255, 187, 51) if i == 4 else (255, 255, 255))
            draw.text((x + bar / 2, floor + 26), label, font=small, fill=(196, 218, 232), anchor="mt")
        draw.line((left - 30, floor, left + 5 * bar + 4 * gap + 30, floor), fill=(120, 170, 190), width=3)
        angle = t * 2 * np.pi / 5
        cx, cy = 230 + 90 * np.cos(angle), 810 + 90 * np.sin(angle)
        draw.ellipse((cx - 22, cy - 22, cx + 22, cy + 22), fill=(255, 187, 51))
        draw.ellipse((140, 720, 320, 900), outline=(196, 218, 232), width=4)
        draw.text((400, 750), f"{int(t) // 60}:{int(t) % 60:02d}", font=clock, fill=(255, 255, 255))
        return image

    command = ["ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{width}x{height}",
               "-r", str(fps), "-i", "-", "-an", "-c:v", "libx264", "-preset", "slow", "-crf", "28", "-pix_fmt", "yuv420p",
               "-movflags", "+faststart", "-r", str(fps), str(path)]
    process = subprocess.Popen(command, stdin=subprocess.PIPE)
    for n in range(fps * seconds):
        process.stdin.write(frame(n / fps).tobytes())
    process.stdin.close()
    if process.wait():
        sys.exit("ffmpeg failed")


